#!/usr/bin/env python3
"""Packs each templates/<slug>/ into templates/dist/<slug>.zip (manifest.json + document.json + optional assets/).

The JSON is generated by ios-editor/Tests/AppModuleTests/TemplateFixturesTests.swift - edit it there,
not here. Zips are deterministic (fixed timestamps), so the sha256 only changes when content does.
"""
import hashlib, json, sys, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DIST = ROOT / "dist"
FIXED_TIME = (2026, 1, 1, 0, 0, 0)


def pack(folder: Path) -> Path:
    for required in ("manifest.json", "document.json"):
        if not (folder / required).is_file():
            sys.exit(f"{folder.name}: missing {required}")
    DIST.mkdir(exist_ok=True)
    target = DIST / f"{folder.name}.zip"
    files = sorted(p for p in folder.rglob("*") if p.is_file() and p.name != ".DS_Store")
    with zipfile.ZipFile(target, "w") as zf:
        for path in files:
            info = zipfile.ZipInfo(path.relative_to(folder).as_posix(), FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, path.read_bytes())
    return target


def main() -> None:
    folders = [p for p in sorted(ROOT.iterdir()) if p.is_dir() and (p / "manifest.json").exists()]
    for folder in folders:
        zip_path = pack(folder)
        data = zip_path.read_bytes()
        manifest = json.loads((folder / "manifest.json").read_text())
        print(f"{zip_path.relative_to(ROOT.parent)}  {len(data)} B  sha256 {hashlib.sha256(data).hexdigest()[:16]}…  slots {len(manifest['slots'])}")


if __name__ == "__main__":
    main()
